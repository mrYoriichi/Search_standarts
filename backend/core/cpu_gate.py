"""Глобальный шлюз для CPU-тяжёлой стадии parse (рендер PDF, Docling, OCR).

Зачем: 3 параллельных parse съедают весь процессор и память — на слабой
машине это лаги и падения (os error 1455 «файл подкачки слишком мал»,
ONNX «bad allocation»). Сетевые стадии (describe, embed) процессор почти
не грузят, поэтому ограничиваем только parse: пока один документ
рендерится, остальные ждут перед шлюзом или работают с API.
"""

import threading

# Semaphore, а не Lock: захотим пускать 2 документа — поменяем одну цифру.
_PARSE_SLOTS = 1

parse_gate = threading.Semaphore(_PARSE_SLOTS)
